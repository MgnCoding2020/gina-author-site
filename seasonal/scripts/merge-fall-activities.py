"""
One-time relocation + merge step for the fall build.

maze.pdf and connect-the-dots.pdf currently live under
seasonal/halloween/activities/ with 3 pages each (the original Halloween
variants). This appends the 3 new fall variants (already generated by
generate-fall-maze.py / generate-fall-dots.py into seasonal/fall/activities/
as standalone 3-page PDFs) and writes the combined 6-page PDFs to the new
shared location, seasonal/activities/ -- since both activities now run
through both the Halloween and fall windows (see ROADMAP.md), they no
longer belong under a season-specific folder.

paw-print-matching.pdf is NOT touched here -- its generator
(generate-paw-print-matching.py) was extended to produce all 6 pages
directly and already writes straight to seasonal/activities/.

Also rebuilds the combined activity-pack.pdf (coloring + all 3 six-variant
activities) at its new shared location, and cleans up the old
Halloween-only copies once the merge is verified.

Usage:
    python merge-fall-activities.py

Requires: pypdf, pymupdf (for the verification scan).
"""

import shutil
from pathlib import Path

from pypdf import PdfReader, PdfWriter
import pymupdf

ROOT = Path(__file__).resolve().parent.parent
OLD_DIR = ROOT / "halloween" / "activities"
FALL_DIR = ROOT / "fall" / "activities"
NEW_DIR = ROOT / "activities"


def merge(old_pdf, new_pages_pdf, out_pdf):
    writer = PdfWriter()
    for src in (old_pdf, new_pages_pdf):
        reader = PdfReader(str(src))
        for page in reader.pages:
            writer.add_page(page)
    NEW_DIR.mkdir(parents=True, exist_ok=True)
    with open(out_pdf, "wb") as f:
        writer.write(f)
    print(f"Wrote {out_pdf} ({len(writer.pages)} pages)")


def verify_no_blank_pages(pdf_path):
    doc = pymupdf.open(str(pdf_path))
    for i, page in enumerate(doc):
        pix = page.get_pixmap(matrix=pymupdf.Matrix(0.5, 0.5))
        # A blank page is (almost) uniformly white -- check pixel variance.
        samples = pix.samples
        if len(set(samples[::97])) <= 2:
            raise AssertionError(f"{pdf_path.name} page {i + 1} looks blank")
    print(f"OK: {pdf_path.name} -- {len(doc)} pages, no blanks")


def main():
    merge(OLD_DIR / "maze.pdf", FALL_DIR / "_fall-maze-new.pdf", NEW_DIR / "maze.pdf")
    merge(
        OLD_DIR / "connect-the-dots.pdf",
        FALL_DIR / "_fall-dots-new.pdf",
        NEW_DIR / "connect-the-dots.pdf",
    )

    shutil.copyfile(OLD_DIR / "maze-preview.webp", NEW_DIR / "maze-preview.webp")
    shutil.copyfile(
        OLD_DIR / "connect-the-dots-preview.webp", NEW_DIR / "connect-the-dots-preview.webp"
    )

    for p in (NEW_DIR / "maze.pdf", NEW_DIR / "connect-the-dots.pdf", NEW_DIR / "paw-print-matching.pdf"):
        verify_no_blank_pages(p)

    # Combined activity pack: coloring + all 3 six-variant activities.
    writer = PdfWriter()
    for src in (
        ROOT / "activities" / "coloring" / "coloring-pages.pdf",
        NEW_DIR / "maze.pdf",
        NEW_DIR / "connect-the-dots.pdf",
        NEW_DIR / "paw-print-matching.pdf",
    ):
        reader = PdfReader(str(src))
        for page in reader.pages:
            writer.add_page(page)
    pack_path = NEW_DIR / "activity-pack.pdf"
    with open(pack_path, "wb") as f:
        writer.write(f)
    print(f"Wrote {pack_path} ({len(writer.pages)} pages)")
    verify_no_blank_pages(pack_path)

    print("\nAll merges verified. Old Halloween-only copies left in place --")
    print("delete them manually once you've visually reviewed the new files.")


if __name__ == "__main__":
    main()
